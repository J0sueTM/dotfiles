#!/usr/bin/env bash

# file: gnome/setup.sh
# GNOME + Forge configured to behave like ../i3/config.
# Idempotent: re-run it any time. Log out and back in after the first run
# (Wayland only loads newly installed extensions on a fresh session).
#
#   FORGE_DIR=~/path/to/forge ./gnome/setup.sh

set -euo pipefail

dotfiles_dir=$(cd "$(dirname "$0")/.." && pwd)
gnome_dir="$dotfiles_dir/gnome"
forge_dir=${FORGE_DIR:-$(dirname "$dotfiles_dir")/forge}
ext_dir="$HOME/.local/share/gnome-shell/extensions"
forge_uuid=forge@jmmaranan.com

wm=org.gnome.desktop.wm.keybindings
shell=org.gnome.shell.keybindings
media=org.gnome.settings-daemon.plugins.media-keys

# ---------------------------------------------------------------- extensions

echo '==> building and installing forge'
# same as forge's `make build install`, minus translations (no make/gettext needed)
forge_dest="$ext_dir/$forge_uuid"
rm -rf "${forge_dest:?}"
mkdir -p "$forge_dest"
(cd "$forge_dir" && cp -r metadata.json resources schemas config lib ./*.js ./*.css LICENSE "$forge_dest")
rm -f "$forge_dest/schemas/gschemas.compiled"
glib-compile-schemas "$forge_dest/schemas"
# lib/prefs/metadata.js is generated by forge's Makefile; the prefs window imports it
{
  echo 'export const developers = Object.entries(['
  git -C "$forge_dir" shortlog -sne HEAD | grep -vE 'dependabot|noreply' |
    sed 's/^[[:space:]]*[0-9]*[[:space:]]*\(.*\) <\(.*\)>/  {name:"\1", email:"\2"},/'
  echo "].reduce((acc, x) => ({ ...acc, [x.email]: acc[x.email] ?? x.name }), {})).map(([email, name]) => name + ' <' + email + '>')"
} >"$forge_dest/lib/prefs/metadata.js"

gsettings set org.gnome.shell disable-user-extensions false
# ubuntu's tiling assistant fights with forge
gnome-extensions disable tiling-assistant@ubuntu.com 2>/dev/null || true
for uuid in "$forge_uuid" workspace-indicator@gnome-shell-extensions.gcampax.github.com; do
  if gnome-extensions info "$uuid" >/dev/null 2>&1; then
    gnome-extensions enable "$uuid"
  else
    # not loaded yet by this session: add it so it starts on next login
    current=$(gsettings get org.gnome.shell enabled-extensions)
    if [[ -d "$ext_dir/$uuid" && $current != *"'$uuid'"* ]]; then
      gsettings set org.gnome.shell enabled-extensions "$(sed "s/^@as \[\]$/[]/; s/\]$/, '$uuid']/; s/\[, /[/" <<<"$current")"
    fi
  fi
done

# --------------------------------------------------------------------- forge

fg() { gsettings --schemadir "$ext_dir/$forge_uuid/schemas" set org.gnome.shell.extensions.forge "$@"; }
fk() { gsettings --schemadir "$ext_dir/$forge_uuid/schemas" set org.gnome.shell.extensions.forge.keybindings "$@"; }

echo '==> configuring forge'
# default_border pixel 0 / gaps commented out
fg focus-border-toggle false
fg window-gap-size 0
# i3 only splits when told to (mod+g / mod+l)
fg auto-split-enabled false
# i3 keeps a tabbed container even with a single window in it
fg auto-exit-tabbed false

# h t n s keybinds
fk window-focus-left  "['<Super>h']"
fk window-focus-down  "['<Super>t']"
fk window-focus-up    "['<Super>n']"
fk window-focus-right "['<Super>s']"

fk window-move-left  "['<Shift><Super>h']"
fk window-move-down  "['<Shift><Super>t']"
fk window-move-up    "['<Shift><Super>n']"
fk window-move-right "['<Shift><Super>s']"

# split h / split v / layout toggle split
fk con-split-horizontal    "['<Super>g']"
fk con-split-vertical      "['<Super>l']"
fk con-split-layout-toggle "['<Ctrl><Shift><Super>l']"

# layout stacking / tabbed
fk con-stacked-layout-toggle "['<Ctrl><Shift><Super>s']"
fk con-tabbed-layout-toggle  "['<Ctrl><Shift><Super>t']"

# floating toggle
fk window-toggle-float "['<Super>space']"

# forge defaults that collide with the bindings above
fk window-swap-left  "[]"
fk window-swap-down  "[]"
fk window-swap-up    "[]"
fk window-swap-right "[]"
fk window-swap-last-active "[]"
for k in one-third-right two-third-right one-third-left two-third-left center; do
  fk "window-snap-$k" "[]"   # ctrl+alt+t etc. belong to apps
done

# ---------------------------------------------------- gnome default conflicts

echo '==> freeing gnome shortcuts used by i3 bindings'
gsettings set $shell focus-active-notification "[]"                   # super+n
gsettings set $shell toggle-quick-settings "[]"                       # super+s
gsettings set $media screensaver "['<Ctrl><Alt>l']"                   # super+l
gsettings set $wm switch-input-source "['XF86Keyboard']"              # super+space
gsettings set $wm switch-input-source-backward "['<Shift>XF86Keyboard']"
gsettings set $wm show-desktop "['<Primary><Super>d', '<Primary><Alt>d']"  # super+d
gsettings set $media screenreader "[]"
# super+<digit> resolves to the same keys as the dvp workspace symbols
for i in 1 2 3 4 5 6 7 8 9; do
  gsettings set $shell "switch-to-application-$i" "[]"
done
gsettings set org.gnome.shell.extensions.dash-to-dock hot-keys false 2>/dev/null || true

# ---------------------------------------------------------- window bindings

echo '==> window and launcher bindings'
gsettings set $wm close "['<Super>c', '<Alt>F4']"                     # kill
gsettings set $wm toggle-fullscreen "['<Super>f']"                    # fullscreen toggle
gsettings set $wm begin-resize "['<Super>r', '<Alt>F8']"              # resize mode (arrows, return/esc)
gsettings set $wm minimize "['<Shift><Super>minus']"                  # move scratchpad (frees super+h)
gsettings set $shell toggle-overview "['<Super>d']"                   # dmenu_run -> type to launch
gsettings set $shell show-screenshot-ui "['Print', '<Shift><Super>d']"  # flameshot gui

# move workspace between monitors -> move window between monitors
# (HDMI-1 sits above eDP-1, so up/down are bound too)
gsettings set $wm move-to-monitor-left  "['<Ctrl><Super>h', '<Super><Shift>Left']"
gsettings set $wm move-to-monitor-right "['<Ctrl><Super>s', '<Super><Shift>Right']"
gsettings set $wm move-to-monitor-up    "['<Ctrl><Super>n', '<Super><Shift>Up']"
gsettings set $wm move-to-monitor-down  "['<Ctrl><Super>t', '<Super><Shift>Down']"

# custom commands: name|binding|command
custom=(
  "terminal|<Super>Return|alacritty"
  "layout-dvp|<Shift><Super>u|$gnome_dir/bin/kbd-layout us+dvp"
  "layout-br-dvorak|<Shift><Super>e|$gnome_dir/bin/kbd-layout br+dvorak"
  "layout-br|<Shift><Super>o|$gnome_dir/bin/kbd-layout br"
)
paths=()
for entry in "${custom[@]}"; do
  IFS='|' read -r name binding command <<<"$entry"
  path="/org/gnome/settings-daemon/plugins/media-keys/custom-keybindings/i3-$name/"
  schema="$media.custom-keybinding:$path"
  gsettings set "$schema" name "i3: $name"
  gsettings set "$schema" binding "$binding"
  gsettings set "$schema" command "$command"
  paths+=("'$path'")
done
gsettings set $media custom-keybindings "[$(IFS=,; echo "${paths[*]}")]"

# --------------------------------------------------------------- workspaces

echo '==> workspaces'
gsettings set org.gnome.mutter dynamic-workspaces false
gsettings set org.gnome.mutter workspaces-only-on-primary false
gsettings set org.gnome.desktop.wm.preferences num-workspaces 5
gsettings set org.gnome.desktop.wm.preferences workspace-names "['α', 'β', 'γ', 'δ', 'ε']"

# bindsym $mod+equal workspace $ws1 ... / $mod+Shift+9 move container ...
go=(equal asterisk parenright plus bracketright)
move=(9 0 2 4 6)
for i in 0 1 2 3 4; do
  gsettings set $wm "switch-to-workspace-$((i + 1))" "['<Super>${go[$i]}']"
  gsettings set $wm "move-to-workspace-$((i + 1))" "['<Super><Shift>${move[$i]}']"
done

# ---------------------------------------------------------------- startup

echo '==> keyboard, display and power'
# setxkbmap us dvp (+ the layouts from the mod+shift+u/e/o bindings)
gsettings set org.gnome.desktop.input-sources sources "[('xkb', 'us+dvp'), ('xkb', 'br+dvorak'), ('xkb', 'br')]"

# redshift -> night light (redshift's default night temperature)
gsettings set org.gnome.settings-daemon.plugins.color night-light-enabled true
gsettings set org.gnome.settings-daemon.plugins.color night-light-schedule-automatic true
gsettings set org.gnome.settings-daemon.plugins.color night-light-temperature 4500

# feh --bg-fill
wallpaper="file://$dotfiles_dir/wallpaper/dark.jpg"
gsettings set org.gnome.desktop.background picture-uri "$wallpaper"
gsettings set org.gnome.desktop.background picture-uri-dark "$wallpaper"
gsettings set org.gnome.desktop.background picture-options zoom

# cpu governor "performance" -> power profile (persists across reboots)
command -v powerprofilesctl >/dev/null && powerprofilesctl set performance || true

echo '==> done. log out and back in if forge was not running yet.'
